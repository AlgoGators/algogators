@dataclass
class ArbitrageBacktestConfig:
    """Configuration for cross-platform arbitrage backtests."""

    strategy_name: str = "Cross-Platform Arbitrage"
    position_size: float = 100.0  # USD per arb, both legs combined
    starting_capital: float = 10000.0
    max_concurrent_positions: int = 20
    max_capital_per_pair: float = 1000.0
    enforce_one_position_per_pair: bool = True

    # Execution (only last/close prices exist historically -> pay a half-spread per leg)
    fill_latency_seconds: int = 60  # Delay between signal and fill
    kalshi_half_spread: float = 0.01
    poly_half_spread: float = 0.0075
    volume_cap_frac: Optional[float] = 0.05  # max contracts as fraction of Kalshi candle volume
    slippage_bps: float = 0.0  # DEPRECATED (superseded by half-spreads); ignored
    hold_to_resolution: bool = True  # settle at resolution when outcomes are provided
    category: str = "other"  # Polymarket fee category

    # Per-fill fee model (Kalshi 0.07*C*P*(1-P) ceil-to-cent; Polymarket by category)
    fee_model: FeeModel = field(default_factory=FeeModel)

    # DEPRECATED profit-fee structures (ignored; kept for import compatibility)
    poly_fees: PlatformFees = field(default_factory=lambda: POLYMARKET_FEES)
    kalshi_fees: PlatformFees = field(default_factory=lambda: KALSHI_FEES)


@dataclass
class ArbitrageTrade:
    """A completed (or open) arbitrage trade spanning two platforms."""

    pair_id: str
    polymarket_id: str
    kalshi_ticker: str
    direction: str  # "buy_kalshi" or "buy_poly"

    # Entry
    entry_time: pd.Timestamp
    entry_ts: int
    entry_poly_price: float
    entry_kalshi_price: float
    entry_spread: float

    # Exit (None if still open)
    exit_time: Optional[pd.Timestamp] = None
    exit_ts: Optional[int] = None
    exit_poly_price: Optional[float] = None
    exit_kalshi_price: Optional[float] = None
    exit_spread: Optional[float] = None
    exit_reason: str = ""

    # Position sizing
    position_size: float = 0.0  # Per side

    # P&L
    gross_pnl: float = 0.0
    poly_fees: float = 0.0
    kalshi_fees: float = 0.0
    slippage: float = 0.0
    net_pnl: float = 0.0
    status: str = "open"  # "open" or "closed"

    # Meta
    signal_confidence: float = 0.0
    z_score: float = 0.0


@dataclass
class ArbitrageBacktestResult:
    """Result bundle for a cross-platform arbitrage backtest."""

    strategy_name: str
    trades_df: pd.DataFrame
    daily_returns: pd.Series
    summary: RunSummary
    pairs_analyzed: int = 0
    total_signals: int = 0

    # Platform-level breakdowns
    poly_pnl: float = 0.0
    kalshi_pnl: float = 0.0
    poly_fees_total: float = 0.0
    kalshi_fees_total: float = 0.0

    # Spread statistics
    avg_entry_spread: float = 0.0
    avg_exit_spread: float = 0.0
    avg_holding_periods: float = 0.0


# ---------------------------------------------------------------------------
# Backtest engine
# ---------------------------------------------------------------------------

def _exec_legs(direction: str, poly_price: float, kalshi_price: float, cfg: "ArbitrageBacktestConfig"):
    """Executable per-contract fills for the two legs (buy at last + half-spread)."""
    if direction == "buy_kalshi":  # Kalshi YES + Polymarket NO
        k_fill = kalshi_price + cfg.kalshi_half_spread
        p_fill = (1.0 - poly_price) + cfg.poly_half_spread
    else:  # Polymarket YES + Kalshi NO
        k_fill = (1.0 - kalshi_price) + cfg.kalshi_half_spread
        p_fill = poly_price + cfg.poly_half_spread
    return min(k_fill, 0.999), min(p_fill, 0.999)


def _leg_values(direction: str, kalshi_yes: float, poly_yes: float):
    """Per-contract value of (kalshi leg, poly leg) given each venue's YES value."""
    if direction == "buy_kalshi":
        return kalshi_yes, 1.0 - poly_yes
    return 1.0 - kalshi_yes, poly_yes


def _get_price(store, kind: str, ident: str, ts: int):
    fn = getattr(store, f"get_{kind}_price", None)
    if fn is None:
        return None
    try:
        return fn(ident, ts)
    except TypeError:
        return None


def _get_last(store, kind: str, ident: str):
    fn = getattr(store, f"get_{kind}_last_price", None)
    return fn(ident) if fn is not None else None


def run_arbitrage_backtest(
    signals: List[ArbitrageSignal],
    price_store: CrossPlatformPriceStore,
    config: Optional[ArbitrageBacktestConfig] = None,
    resolutions: Optional[Dict[str, Dict[str, Any]]] = None,
) -> ArbitrageBacktestResult:
    """
    Run a signal-driven cross-platform arbitrage backtest.

    Each entry opens a two-legged position bought at executable prices
    (last + half-spread per leg; per-fill fees from ``config.fee_model``):
    - "buy_kalshi": buy YES on Kalshi + buy NO on Polymarket
    - "buy_poly":   buy YES on Polymarket + buy NO on Kalshi

    ``position_size`` is the USD committed per arb (both legs combined).
    Capital stays locked until the position is closed (exit signal, sold at
    last - half-spread with exit fees) or, with ``hold_to_resolution`` and a
    known resolution, until resolution, where EACH leg settles at its own
    venue's outcome (0/1). Positions still open at the end are marked at the
    last available price and flagged ``marked_to_last`` - they are not dropped.

    Args:
        signals: ArbitrageSignal list (entry/exit), any order.
        price_store: object with get_polymarket_price / get_kalshi_price (as-of),
            optionally get_*_last_price and get_kalshi_volume.
        config: ArbitrageBacktestConfig.
        resolutions: {pair_id: {"k_outcome": 0/1, "pm_outcome": 0/1, "resolve_ts": int}}
    """
    import heapq

    if config is None:
        config = ArbitrageBacktestConfig()
    resolutions = resolutions or {}
    fm = config.fee_model

    trades: List[Dict[str, Any]] = []
    open_positions: Dict[str, Dict[str, Any]] = {}
    pending_settle: List[tuple] = []  # (resolve_ts, seq, pair_id)
    cash = float(config.starting_capital)
    traded_pairs: set = set()
    seq = 0

    def _close(pos: Dict[str, Any], exit_ts: int, k_val: float, p_val: float, reason: str,
               status: str, exit_fees: bool, marked: bool) -> None:
        nonlocal cash
        C = pos["contracts"]
        if exit_fees:
            k_exit_fee = fm.kalshi(C, k_val)
            p_exit_fee = fm.poly(C, p_val, config.category)
        else:
            k_exit_fee = p_exit_fee = 0.0
        kalshi_pnl = C * (k_val - pos["k_fill"])
        poly_pnl = C * (p_val - pos["p_fill"])
        k_fees = pos["k_entry_fee"] + k_exit_fee
        p_fees = pos["p_entry_fee"] + p_exit_fee
        gross = kalshi_pnl + poly_pnl
        net = gross - k_fees - p_fees
        proceeds = C * (k_val + p_val) - k_exit_fee - p_exit_fee
        cash += proceeds
        lock_days = max(exit_ts - pos["entry_ts"], 0) / 86400.0
        trades.append({
            "pair_id": pos["pair_id"],
            "polymarket_id": pos["polymarket_id"],
            "kalshi_ticker": pos["kalshi_ticker"],
            "direction": pos["direction"],
            "entry_time": pd.to_datetime(pos["entry_ts"], unit="s"),
            "entry_ts": pos["entry_ts"],
            "entry_poly_price": pos["entry_poly_price"],
            "entry_kalshi_price": pos["entry_kalshi_price"],
            "entry_spread": pos["entry_poly_price"] - pos["entry_kalshi_price"],
            "k_fill": pos["k_fill"],
            "p_fill": pos["p_fill"],
            "exit_time": pd.to_datetime(exit_ts, unit="s"),
            "exit_ts": exit_ts,
            "exit_kalshi_leg_value": k_val,
            "exit_poly_leg_value": p_val,
            "exit_reason": reason,
            "contracts": C,
            "position_size": pos["cost"],
            "capital_locked": pos["cost"],
            "lock_days": lock_days,
            "poly_pnl": poly_pnl,
            "kalshi_pnl": kalshi_pnl,
            "gross_pnl": gross,
            "poly_fees": p_fees,
            "kalshi_fees": k_fees,
            "total_fees": k_fees + p_fees,
            "net_pnl": net,
            "return_on_locked": net / pos["cost"] if pos["cost"] > 0 else 0.0,
            "ann_return_on_locked": (net / pos["cost"]) * 365.0 / max(lock_days, 1 / 24) if pos["cost"] > 0 else 0.0,
            "status": status,
            "marked_to_last": marked,
            "signal_confidence": pos["signal_confidence"],
            "z_score": pos["z_score"],
            "datetime": pd.to_datetime(pos["entry_ts"], unit="s"),
            "date": pd.to_datetime(pos["entry_ts"], unit="s").date(),
        })

    def _settle_due(now: int) -> None:
        while pending_settle and pending_settle[0][0] <= now:
            rts, _, pid = heapq.heappop(pending_settle)
            pos = open_positions.pop(pid, None)
            if pos is None:
                continue
            r = resolutions[pid]
            k_val, p_val = _leg_values(pos["direction"], float(r["k_outcome"]), float(r["pm_outcome"]))
            _close(pos, int(rts), k_val, p_val, "resolution", "settled", False, False)

    for signal in sorted(signals, key=lambda x: x.timestamp):
        pair_id = signal.pair_id
        _settle_due(signal.timestamp)
        res = resolutions.get(pair_id)
        hold = config.hold_to_resolution and res is not None and pd.notna(res.get("k_outcome")) \
            and pd.notna(res.get("pm_outcome"))

        if signal.signal_type == "entry":
            if config.enforce_one_position_per_pair and pair_id in traded_pairs:
                continue
            if pair_id in open_positions or len(open_positions) >= config.max_concurrent_positions:
                continue
            if res is not None and signal.timestamp >= res.get("resolve_ts", float("inf")):
                continue
            fill_ts = signal.timestamp + config.fill_latency_seconds
            pf = _get_price(price_store, "polymarket", signal.polymarket_id, fill_ts)
            kf = _get_price(price_store, "kalshi", signal.kalshi_ticker, fill_ts)
            poly_px = pf["price"] if pf else signal.poly_price
            kal_px = kf["price"] if kf else signal.kalshi_price
            if not (0 < poly_px < 1 and 0 < kal_px < 1):
                continue
            direction = signal.direction
            k_fill, p_fill = _exec_legs(direction, poly_px, kal_px, config)
            if k_fill + p_fill >= 1.0:
                continue  # edge gone at executable prices
            budget = min(config.position_size, cash, config.max_capital_per_pair)
            per = k_fill + p_fill + fm.kalshi_per_contract(k_fill) + fm.poly_per_contract(p_fill, config.category)
            C = int(np.floor(budget / per + 1e-9)) if budget > 0 else 0
            kvol_fn = getattr(price_store, "get_kalshi_volume", None)
            if config.volume_cap_frac is not None and kvol_fn is not None:
                kvol = kvol_fn(signal.kalshi_ticker, fill_ts)
                if kvol is not None and not pd.isna(kvol):
                    C = min(C, int(np.floor(config.volume_cap_frac * kvol + 1e-9)))

            def _cost(n):
                kfee = fm.kalshi(n, k_fill)
                pfee = fm.poly(n, p_fill, config.category)
                return n * (k_fill + p_fill) + kfee + pfee, kfee, pfee

            while C > 0 and _cost(C)[0] > budget + 1e-9:
                C -= 1
            if C <= 0:
                continue
            cost, kfee, pfee = _cost(C)
            open_positions[pair_id] = {
                "pair_id": pair_id,
                "polymarket_id": signal.polymarket_id,
                "kalshi_ticker": signal.kalshi_ticker,
                "direction": direction,
                "entry_ts": int(fill_ts),
                "entry_poly_price": poly_px,
                "entry_kalshi_price": kal_px,
                "k_fill": k_fill,
                "p_fill": p_fill,
                "contracts": C,
                "k_entry_fee": kfee,
                "p_entry_fee": pfee,
                "cost": cost,
                "signal_confidence": signal.confidence,
                "z_score": signal.z_score,
            }
            cash -= cost
            traded_pairs.add(pair_id)
            if hold:
                heapq.heappush(pending_settle, (int(res["resolve_ts"]), seq, pair_id))
                seq += 1

        elif signal.signal_type == "exit":
            if pair_id not in open_positions or hold:
                continue  # held to resolution: exit signals ignored
            pos = open_positions.pop(pair_id)
            exit_ts = signal.timestamp + config.fill_latency_seconds
            pe = _get_price(price_store, "polymarket", pos["polymarket_id"], exit_ts)
            ke = _get_price(price_store, "kalshi", pos["kalshi_ticker"], exit_ts)
            poly_px = pe["price"] if pe else signal.poly_price
            kal_px = ke["price"] if ke else signal.kalshi_price
            k_val, p_val = _leg_values(pos["direction"], kal_px, poly_px)
            # sell each leg at its bid = value - half-spread
            k_val = max(k_val - config.kalshi_half_spread, 0.0)
            p_val = max(p_val - config.poly_half_spread, 0.0)
            _close(pos, int(exit_ts), k_val, p_val, signal.metadata.get("exit_reason", "signal"),
                   "closed", True, False)

    _settle_due(2**62)

    # Still-open positions: settle if resolution known, else mark at last price (flagged)
    for pair_id, pos in list(open_positions.items()):
        res = resolutions.get(pair_id)
        if res is not None and pd.notna(res.get("k_outcome")) and pd.notna(res.get("pm_outcome")):
            k_val, p_val = _leg_values(pos["direction"], float(res["k_outcome"]), float(res["pm_outcome"]))
            _close(pos, int(res.get("resolve_ts", pos["entry_ts"])), k_val, p_val, "resolution", "settled",
                   False, False)
            continue
        kl = _get_last(price_store, "kalshi", pos["kalshi_ticker"])
        pl = _get_last(price_store, "polymarket", pos["polymarket_id"])
        kal_px = kl["price"] if kl else pos["entry_kalshi_price"]
        poly_px = pl["price"] if pl else pos["entry_poly_price"]
        mark_ts = max([x["timestamp"] for x in (kl, pl) if x] or [pos["entry_ts"]])
        k_val, p_val = _leg_values(pos["direction"], kal_px, poly_px)
        _close(pos, int(mark_ts), k_val, p_val, "open", "open", False, True)
    open_positions.clear()

    trades_df = pd.DataFrame(trades)
    if not trades_df.empty:
        trades_df = trades_df.sort_values("entry_ts").reset_index(drop=True)
        trades_df["cumulative_pnl"] = trades_df["net_pnl"].cumsum()

    realized = trades_df[trades_df["status"] != "open"] if not trades_df.empty else trades_df
    daily_returns = pd.Series(dtype=float)
    if not realized.empty:
        daily_returns = compute_daily_returns(trades_df=realized, starting_capital=config.starting_capital)

    summary = _build_arb_summary(trades_df, config)
    result = ArbitrageBacktestResult(
        strategy_name=config.strategy_name,
        trades_df=trades_df,
        daily_returns=daily_returns,
        summary=summary,
        total_signals=len(signals),
        poly_pnl=realized["poly_pnl"].sum() if not realized.empty else 0.0,
        kalshi_pnl=realized["kalshi_pnl"].sum() if not realized.empty else 0.0,
        poly_fees_total=realized["poly_fees"].sum() if not realized.empty else 0.0,
        kalshi_fees_total=realized["kalshi_fees"].sum() if not realized.empty else 0.0,
        avg_entry_spread=realized["entry_spread"].abs().mean() if not realized.empty else 0.0,
        avg_exit_spread=0.0,
    )
    return result


def _build_arb_summary(
    trades_df: pd.DataFrame,
    config: ArbitrageBacktestConfig,
) -> RunSummary:
    """Build RunSummary from arbitrage trades."""
    metadata = RunMetadata(
        strategy_name=config.strategy_name,
        run_type="arbitrage_backtest",
        starting_capital=config.starting_capital,
        position_size=config.position_size,
    )

    metrics = RunMetrics()
    diagnostics = RunDiagnostics()

    if trades_df.empty:
        return RunSummary(metadata=metadata, metrics=metrics, diagnostics=diagnostics)

    closed = trades_df[trades_df["status"] != "open"]  # closed or settled

    metrics.total_trades = len(closed)
    metrics.unique_markets = trades_df["pair_id"].nunique()
    metrics.open_positions = len(trades_df[trades_df["status"] == "open"])

    if not closed.empty:
        winners = closed[closed["net_pnl"] > 0]
        losers = closed[closed["net_pnl"] <= 0]

        metrics.winning_trades = len(winners)
        metrics.losing_trades = len(losers)
        metrics.win_rate = len(winners) / len(closed) if len(closed) > 0 else 0.0

        metrics.total_gross_pnl = closed["gross_pnl"].sum()
        metrics.total_net_pnl = closed["net_pnl"].sum()
        metrics.total_costs = closed["total_fees"].sum()

        metrics.avg_win = winners["net_pnl"].mean() if not winners.empty else 0.0
        metrics.avg_loss = losers["net_pnl"].mean() if not losers.empty else 0.0

        total_wins = winners["net_pnl"].sum() if not winners.empty else 0.0
        total_losses = abs(losers["net_pnl"].sum()) if not losers.empty else 0.0
        metrics.profit_factor = (
            total_wins / total_losses if total_losses > 0 else float("inf")
        )

        metrics.roi_pct = (
            (metrics.total_net_pnl / config.starting_capital) * 100
        )

        # Position sizing stats
        metrics.avg_position_size = closed["position_size"].mean()  # both legs (USD locked)
        metrics.max_position_size = closed["position_size"].max()

        # Holding time
        if "entry_time" in closed.columns and "exit_time" in closed.columns:
            durations = closed["exit_time"] - closed["entry_time"]
            valid_durations = durations.dropna()
            if not valid_durations.empty:
                metrics.avg_holding_days = (
                    valid_durations.dt.total_seconds().mean() / 86400
                )

        # Sharpe ratio from daily returns
        if not closed.empty and "date" in closed.columns:
            daily_pnl = closed.groupby("date")["net_pnl"].sum()
            if len(daily_pnl) > 1:
                daily_ret = daily_pnl / config.starting_capital
                metrics.sharpe_ratio = (
                    daily_ret.mean() / daily_ret.std() * np.sqrt(365)
                    if daily_ret.std() > 0 else 0.0
                )

        # Max drawdown
        cum_pnl = closed["net_pnl"].cumsum()
        running_max = cum_pnl.cummax()
        drawdown = running_max - cum_pnl
        metrics.max_drawdown = drawdown.max() if not drawdown.empty else 0.0

    return RunSummary(metadata=metadata, metrics=metrics, diagnostics=diagnostics)


