"""Generate docs/SCRIPTS_STATUS.md: every script under scripts/, its study family, status and data sources.

Status comes from the strategy catalog (docs/strategies/catalog.json, built by build_strategy_catalog.py): a
script's family is *active* while any of its strategies is unproven, a candidate, capacity-capped or live, and
*archived* when every one is rejected or invalid. Scripts outside a study family are grouped by folder. A script
reading the deleted Polymarket monthly extract is served the same columns from trades.parquet
(src/data_quality/legacy_pm_trades.py), so nothing is flagged as needing removed data. Data sources are detected from the source text, so treat them as a guide.

    uv run python scripts/research/build_script_status.py          # rewrite docs/SCRIPTS_STATUS.md
    uv run python scripts/research/build_script_status.py --check  # exit 1 if the file is out of date
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from collections import Counter, defaultdict
from pathlib import Path

from doc_revision import stamp

ROOT = Path(__file__).resolve().parents[2]
CATALOG = ROOT / "docs/strategies/catalog.json"
OUT = ROOT / "docs/SCRIPTS_STATUS.md"
ACTIVE = {"unproven", "candidate", "capacity_capped", "live"}

SOURCES = [  # (label, regex over the script text)
    ("lake", r"predict_ngin(\.| import )lake|lake\.connect\("),
    ("kalshi tape", r"tape_sql\(|tapes\.kalshi|kalshi_tape import"),
    ("polymarket fills", r"clean_trades_sql\(|tapes\.polymarket|polymarket_tape import"),
    ("kalshi trades_fixed (direct)", r"trades_fixed(?!_ext)[/\"' ]"),
    ("polymarket raw", r"polymarket/(trades|orderfilled|markets)\.parquet|\"polymarket\" / \"(trades|orderfilled)"),
    ("recorder books", r"live_books"),
    ("Kalshi API", r"api\.elections\.kalshi\.com|KalshiReadClient|kalshi_flb_api"),
    ("Polymarket API", r"gamma-api\.polymarket|clob\.polymarket|data-api\.polymarket"),
    ("vendor cache", r"data/vendor|\"vendor\""),
]
NEEDS_DATA = re.compile(r"(?!)")  # nothing needs removed data any more (compatibility view, 2026-10-17)


def load_families() -> tuple[dict, dict]:
    cat = json.loads(CATALOG.read_text(encoding="utf-8"))
    fam_status: dict = defaultdict(set)
    for s in cat["strategies"]:
        if s.get("family"):
            fam_status[s["family"]].add(s["status"])
    script_fam = {}
    for fam, info in cat["families"].items():
        for p in info.get("scripts", []):
            script_fam[p] = (fam, info.get("title", fam))
    return script_fam, fam_status


def classify(statuses: set) -> str:
    if not statuses:
        return "no ledger entry"
    return "active" if statuses & ACTIVE else "archived"


def render() -> str:
    script_fam, fam_status = load_families()
    rows = []
    for p in sorted(ROOT.glob("scripts/**/*.py")):
        rel = p.relative_to(ROOT).as_posix()
        if "/__pycache__/" in rel or rel.endswith("__init__.py"):
            continue
        text = p.read_text(encoding="utf-8", errors="replace")
        srcs = [label for label, rx in SOURCES if re.search(rx, text)]
        fam, title = script_fam.get(rel, (None, None))
        if fam:
            status = classify(fam_status.get(fam, set()))
        else:
            status = {"scripts/data": "data pipeline", "scripts/live": "live / paper",
                      "scripts/analysis": "legacy", "scripts/backtest": "legacy"}.get("/".join(rel.split("/")[:2]),
                                                                                       "unassigned")
        if NEEDS_DATA.search(text) and "_deleted_data.py" not in rel:
            status += ", needs removed data"
        rows.append((rel, fam or "", status, ", ".join(srcs)))
    counts = Counter(r[2] for r in rows)
    lines = ["# Script status", "",
             "Generated by `scripts/research/build_script_status.py` from docs/strategies/catalog.json; do not edit.",
             "Status: *active* = the study family has an unproven, candidate, capacity-capped or live strategy;",
             "*archived* = every strategy in it was rejected or invalid (code kept for audit, not maintained);",
             "Old code that read datasets deleted on 2026-10-17 is served from what remains (docs/DATA_LAKE.md).",
             "Data sources are detected from the source text. New code should read data through",
             "`predict_ngin.lake` / `predict_ngin.tapes` (docs/DATA_LAKE.md).", "",
             "| Status | Scripts |", "|---|---|"]
    lines += [f"| {k} | {v} |" for k, v in sorted(counts.items(), key=lambda kv: -kv[1])]
    lines += ["", "| Script | Family | Status | Data sources |", "|---|---|---|---|"]
    lines += [f"| `{r}` | {f} | {s} | {d} |" for r, f, s, d in rows]
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = stamp(render(), OUT.read_text(encoding="utf-8") if OUT.exists() else None)
    if a.check:
        ok = OUT.exists() and OUT.read_text(encoding="utf-8") == text
        print("up to date" if ok else f"{OUT} is out of date; rerun without --check")
        return 0 if ok else 1
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
