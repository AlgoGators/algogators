"""Keep open strategies (working or to-do) out of the public repo; publish only rejected / invalid ones.

Policy (user decision, 2026-10-17): a study family is *open* while any of its strategies is unproven,
capacity-capped, a candidate or live. Everything of an open family - scripts, docs, ledger entries, tests - stays
on the maintainer's disk but is not committed. A family becomes public once every strategy in it is rejected or
invalid: re-run this script and its files leave the private list.

Generated catalog files that describe open strategies (ledger, catalog, next steps, results database) are private
too; docs/strategies/REJECTED.md stays public.

A public file that imports private code becomes private too (privacy first), so the public repo never has a
dangling import - except infrastructure (predict_ngin/, src/, scripts/data/, the core golden tests), whose imports
of private modules must be optional (the golden tests skip those comparisons in a public clone). The script edits the block between the markers in .gitignore and, with
--apply, untracks private files with `git rm --cached` (the files stay on disk; history is not rewritten).

    uv run python scripts/research/build_private_split.py            # dry run: report only
    uv run python scripts/research/build_private_split.py --apply    # update .gitignore and untrack
"""
from __future__ import annotations

import argparse
import ast
import collections
import re
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CATALOG = ROOT / "docs/strategies/catalog.json"
OPEN = {"unproven", "capacity_capped", "candidate", "live"}
BEGIN = "# >>> private strategies (generated by scripts/research/build_private_split.py; do not edit) >>>"
END = "# <<< private strategies <<<"
ALWAYS_PRIVATE = [  # generated indexes and stores that describe every strategy, open ones included
    "docs/RESEARCH_LEDGER.md", "docs/strategies/catalog.json", "docs/strategies/families.yaml",
    "docs/strategies/PROMISING.md", "docs/strategies/NEXT_STEPS.md", "docs/strategies/CODE_ARCHIVE.md",
    "docs/SCRIPTS_STATUS.md", "backtests/results.db", "research/trials.csv",
]
# work in progress that has no ledger entry yet (new studies start as to-do, so private)
WIP_GLOBS = ["scripts/research/mmq_*", "docs/MMQ_*", "data/research_reports/mmq_*", "scripts/research/ledger_entries/mmq*.yaml"]
EXTRA_PRIVATE = {  # promoted rules of open strategies that live outside scripts/
    "perps": ["predict_ngin/paper/strategies/perps_carry.py", "scripts/live/perps_carry_paper.py"],
    "wxlive": ["predict_ngin/paper/strategies/wxlive.py"],
    "lipaudit": ["scripts/research/props_maker_markout.py"],  # kalshi_sports_prop_combo_lip
    "v3": ["src/backtest_v3/"],  # the v3 engine and its strategies
}


def tracked() -> set[str]:
    out = subprocess.run(["git", "ls-files"], cwd=ROOT, capture_output=True, text=True, check=True).stdout
    return set(out.split())


def private_paths(cat: dict) -> tuple[set[str], list[str]]:
    status = collections.defaultdict(set)
    for s in cat["strategies"]:
        status[s.get("family")].add(s["status"])
    open_f = sorted(f for f, v in status.items() if f and v & OPEN)
    paths: set[str] = set(ALWAYS_PRIVATE)
    for f in open_f:
        info = cat["families"].get(f, {})
        for k in ("scripts", "docs", "tests"):
            paths.update(info.get(k, []))
        paths.update(f"scripts/research/ledger_entries/{x}" for x in info.get("ledger_files", []))
        paths.update(EXTRA_PRIVATE.get(f, []))
    for s in cat["strategies"]:
        if s["status"] in OPEN:
            paths.update(p for p in (s.get("evidence_paths") or []) if p)
            if s.get("ledger_file"):
                paths.add(f"scripts/research/ledger_entries/{s['ledger_file']}")
    return paths, open_f


def on_disk(cat: dict) -> set[str]:
    """Files present locally that may be private: untracked ones are invisible to `git ls-files`."""
    out = set()
    for pat in ("scripts/**/*.py", "src/**/*.py", "tests/**/*.py", "predict_ngin/**/*.py", "docs/**/*.md",
                "scripts/research/ledger_entries/*.yaml"):
        out |= {q.relative_to(ROOT).as_posix() for q in ROOT.glob(pat) if q.is_file() and "__pycache__" not in q.parts}
    paths, _ = private_paths(cat)
    out |= {x for x in paths if (ROOT / x).is_file()}
    return out


def module_index(files: set[str]) -> dict[str, str]:
    """Import name -> path for modules a script can import (scripts/research flat names, dotted src/ / tests/)."""
    idx = {}
    for p in files:
        if not p.endswith(".py"):
            continue
        q = Path(p)
        if q.parts[:2] == ("scripts", "research") or q.parts[:2] == ("scripts", "live"):
            idx.setdefault(q.stem, p)
        dotted = ".".join(q.with_suffix("").parts)
        idx[dotted] = p
        if q.parts[0] == "src":
            idx[".".join(q.with_suffix("").parts[1:])] = p
        if q.name == "__init__.py":
            idx[".".join(q.parent.parts)] = p
            if q.parts[0] == "src":
                idx[".".join(q.parent.parts[1:])] = p
    return idx


def imports_of(path: Path) -> set[str]:
    """Dotted names a file imports (relative imports resolved), plus repo paths it loads by file name."""
    text = path.read_text(encoding="utf-8", errors="replace")
    try:
        tree = ast.parse(text)
    except SyntaxError:
        return set()
    rel = path.relative_to(ROOT).with_suffix("")
    pkg = list(rel.parts[:-1]) if path.name != "__init__.py" else list(rel.parts[:-1])
    names = set()
    for n in ast.walk(tree):
        if isinstance(n, ast.Import):
            names.update(a.name for a in n.names)
        elif isinstance(n, ast.ImportFrom):
            if n.level:  # from ..x import y -> resolve against this file's package
                base = pkg[: len(pkg) - (n.level - 1)] if n.level > 1 else pkg
                mod = ".".join(base + ([n.module] if n.module else []))
            else:
                mod = n.module or ""
            if mod:
                names.add(mod)
                names.update(f"{mod}.{a.name}" for a in n.names)
    out = set()
    for nm in names:  # a.b.c also needs a.b and a
        parts = nm.split(".")
        out.update(".".join(parts[:i]) for i in range(1, len(parts) + 1))
    # only real path construction (prose mentions of "scripts/research/x.py" are not loads)
    for m in re.finditer(r'"scripts"\s*/\s*"(research|live)"\s*/\s*"([\w.]+\.py)"', text):
        out.add(f"path:scripts/{m.group(1)}/{m.group(2)}")
    return out


PROTECTED = ("predict_ngin/", "src/", "scripts/data/", "tests/unit/test_golden_", "tests/conftest")
NOT_PROTECTED = ("src/backtest_v3/", "tests/unit/test_golden_paper_strategies.py")


def protected(p: str) -> bool:
    """Public infrastructure: never made private. If it imports private code, that import must be optional."""
    return p.startswith(PROTECTED) and not p.startswith(NOT_PROTECTED)


def split(cat: dict, files: set[str]):
    private, open_f = private_paths(cat)
    dirs = [d.rstrip("/") + "/" for d in private if not Path(d).suffix]
    private = {p for p in files if p in private or any(p.startswith(d) for d in dirs)}
    idx = module_index(files)
    pulled: dict[str, str] = {}  # public file -> private module it imports (file becomes private too)
    needs_optional: dict[str, set[str]] = collections.defaultdict(set)
    changed = True
    while changed:  # a public file that imports private code becomes private, unless it is infrastructure
        changed = False
        for p in sorted(f for f in files if f.endswith(".py") and f not in private):
            names = imports_of(ROOT / p)
            deps = {idx[nm] for nm in names if idx.get(nm) in private}
            deps |= {nm[5:] for nm in names if nm.startswith("path:") and nm[5:] in private}
            if not deps:
                continue
            if protected(p):
                needs_optional[p] |= deps
            else:
                private.add(p)
                pulled[p] = sorted(deps)[0]
                changed = True
    return sorted(private), open_f, pulled, needs_optional
def write_gitignore(private: list[str], open_f: list[str]) -> None:
    dirs = {d for f in open_f for d in EXTRA_PRIVATE.get(f, []) if d.endswith("/")}  # whole folders, any file type
    private = sorted(set(private) | set(WIP_GLOBS) | dirs)
    gi = ROOT / ".gitignore"
    text = gi.read_bytes().decode("utf-8")
    nl = "\r\n" if "\r\n" in text else "\n"
    block = nl.join([BEGIN] + ["/" + p for p in private] + [END])
    if BEGIN in text:
        a, b = text.index(BEGIN), text.index(END) + len(END)
        text = text[:a] + block + text[b:]
    else:
        text = text.rstrip("\r\n") + nl + nl + block + nl
    gi.write_bytes(text.encode("utf-8"))


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--apply", action="store_true")
    a = ap.parse_args()
    cat = json.loads(CATALOG.read_text(encoding="utf-8"))
    files = tracked() | on_disk(cat)
    private, open_f, pulled, needs_optional = split(cat, files)
    by_dir = collections.Counter("/".join(p.split("/")[:2]) for p in private)
    print(f"open families ({len(open_f)}): {', '.join(open_f)}")
    print(f"private files: {len(private)}  {dict(by_dir.most_common(8))}")
    print(f"public files made private because they import private code ({len(pulled)}):")
    for q, dep in sorted(pulled.items()):
        print(f"  {q}   -> {dep}")
    print(f"infrastructure that imports private code; those imports must be optional ({len(needs_optional)}):")
    for q, deps in sorted(needs_optional.items()):
        print(f"  {q}   -> {', '.join(sorted(deps))}")
    if a.apply:
        write_gitignore(private, open_f)
        tr = sorted(set(private) & tracked())
        for i in range(0, len(tr), 200):
            subprocess.run(["git", "rm", "--cached", "-q", "--", *tr[i:i + 200]], cwd=ROOT, check=True)
        print(f"untracked {len(tr)} files; .gitignore updated (files stay on disk)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
